using Labsync.Models.Data;
using LabSync.Areas.LabTechnician.Models;
using LabSync.Models;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;

namespace LabSync.Areas.LabTechnician.Controllers
{
    [Area("LabTechnician")]
    [Authorize]
    public class ReportsController : Controller
    {
        private readonly ApplicationDbContext _context;
        private readonly IWebHostEnvironment _environment;


        // =========================================================
        // CONSTRUCTOR
        // =========================================================

        public ReportsController(
            ApplicationDbContext context,
            IWebHostEnvironment environment)
        {
            _context = context;
            _environment = environment;
        }


        // =========================================================
        // INDEX
        // =========================================================

        [HttpGet]
        public async Task<IActionResult> Index(
            string? appointmentId)
        {
            appointmentId =
                string.IsNullOrWhiteSpace(
                    appointmentId)
                    ? null
                    : appointmentId.Trim();


            // =====================================================
            // LOAD REPORTS FROM DATABASE
            // =====================================================

            var reports =
                await _context.Database
                    .SqlQueryRaw<ReportListRowViewModel>(
                        """
                        SELECT

                            r.Id AS Id,

                            r.AppointmentId
                                AS AppointmentId,

                            a.AppointmentCode
                                AS AppointmentCode,

                            a.AppointmentDate
                                AS AppointmentDate,

                            a.AppointmentTime
                                AS AppointmentTime,


                            -- PATIENT

                            p.PatientCode
                                AS PatientCode,

                            CONCAT(
                                p.FirstName,
                                ' ',
                                p.LastName
                            ) AS PatientName,

                            p.Phone
                                AS Phone,


                            -- GENERATED BY

                            r.GeneratedBy
                                AS GeneratedBy,

                            gu.Email
                                AS GeneratedByEmail,

                            r.GeneratedDate
                                AS GeneratedDate,


                            -- PDF

                            r.PdfPath
                                AS PdfPath,


                            -- APPROVAL

                            r.ApprovalStatusId
                                AS ApprovalStatusId,

                            ras.StatusName
                                AS ApprovalStatusName,

                            r.ApprovedBy
                                AS ApprovedBy,

                            au.Email
                                AS ApprovedByEmail,

                            r.ApprovalDate
                                AS ApprovalDate,


                            -- DELIVERY

                            r.IsDelivered
                                AS IsDelivered,

                            r.DeliveredAt
                                AS DeliveredAt,

                            r.DeliveredBy
                                AS DeliveredBy

                        FROM Reports r

                        INNER JOIN Appointments a
                            ON a.Id =
                               r.AppointmentId

                        INNER JOIN Patients p
                            ON p.Id =
                               a.PatientId

                        INNER JOIN Users gu
                            ON gu.Id =
                               r.GeneratedBy

                        LEFT JOIN Users au
                            ON au.Id =
                               r.ApprovedBy

                        INNER JOIN ReportApprovalStatuses ras
                            ON ras.Id =
                               r.ApprovalStatusId

                        WHERE

                            (
                                NULLIF(
                                    {0},
                                    ''
                                ) IS NULL

                                OR

                                UPPER(
                                    ISNULL(
                                        a.AppointmentCode,
                                        ''
                                    )
                                )
                                LIKE
                                '%' +
                                UPPER({0}) +
                                '%'
                            )

                        ORDER BY

                            r.GeneratedDate DESC,

                            r.Id DESC
                        """,

                        appointmentId ?? ""
                    )
                    .ToListAsync();


            // =====================================================
            // VIEW DATA
            // =====================================================

            ViewBag.AppointmentId =
                appointmentId ?? "";


            ViewData["ActiveMenu"] =
                "Reports";


            // =====================================================
            // RETURN VIEW
            // =====================================================

            return View(
                "Index",
                reports
            );
        }


        // =========================================================
        // DETAILS
        // =========================================================

        [HttpGet]
        public async Task<IActionResult> Details(
            int id)
        {
            if (id <= 0)
            {
                TempData["Error"] =
                    "Invalid report.";

                return RedirectToAction(
                    nameof(Index)
                );
            }


            // =====================================================
            // LOAD ALL TEST DETAILS OF THIS REPORT
            // =====================================================

            var reportDetails =
                await _context.Database
                    .SqlQueryRaw<ReportTestDetailsViewModel>(
                        """
                        SELECT

                            -- REPORT

                            r.Id
                                AS ReportId,

                            r.AppointmentId
                                AS AppointmentId,


                            -- APPOINTMENT

                            a.AppointmentCode
                                AS AppointmentCode,

                            a.AppointmentDate
                                AS AppointmentDate,

                            a.AppointmentTime
                                AS AppointmentTime,


                            -- PATIENT

                            p.PatientCode
                                AS PatientCode,

                            CONCAT(
                                p.FirstName,
                                ' ',
                                p.LastName
                            ) AS PatientName,

                            p.Phone
                                AS Phone,

                            p.Email
                                AS Email,


                            -- TEST

                            at.Id
                                AS AppointmentTestId,

                            t.TestCode
                                AS TestCode,

                            t.TestName
                                AS TestName,

                            t.Unit
                                AS Unit,


                            -- REFERENCE RANGE

                            rr.ReferenceRange
                                AS ReferenceRange,

                            rr.Description
                                AS ReferenceRangeDescription,


                            -- RESULT

                            tr.ResultValue
                                AS ResultValue,

                            tr.ResultInterpretation
                                AS ResultInterpretation,

                            tr.Remarks
                                AS Remarks,

                            rs.StatusName
                                AS ResultStatusName,

                            tr.ResultDate
                                AS ResultDate

                        FROM Reports r

                        INNER JOIN Appointments a
                            ON a.Id =
                               r.AppointmentId

                        INNER JOIN Patients p
                            ON p.Id =
                               a.PatientId

                        INNER JOIN AppointmentTests at
                            ON at.AppointmentId =
                               a.Id

                        INNER JOIN Tests t
                            ON t.Id =
                               at.TestId

                        LEFT JOIN ReferenceRanges rr
                            ON rr.Id =
                               t.ReferenceRangeId

                        LEFT JOIN TestResults tr
                            ON tr.AppointmentTestId =
                               at.Id

                        LEFT JOIN ResultStatuses rs
                            ON rs.Id =
                               tr.ResultStatusId

                        WHERE
                            r.Id = {0}

                        ORDER BY
                            at.Id ASC
                        """,

                        id
                    )
                    .ToListAsync();


            // =====================================================
            // REPORT NOT FOUND
            // =====================================================

            if (
                reportDetails == null
                ||
                reportDetails.Count == 0
            )
            {
                TempData["Error"] =
                    "Report details were not found.";

                return RedirectToAction(
                    nameof(Index)
                );
            }


            ViewData["ActiveMenu"] =
                "Reports";


            return View(
                "Details",
                reportDetails
            );
        }


        // =========================================================
        // VIEW PDF
        // =========================================================

        [HttpGet]
        public async Task<IActionResult> ViewPdf(
            int id)
        {
            if (id <= 0)
            {
                return NotFound();
            }


            // =====================================================
            // GET PDF PATH
            // =====================================================

            var report =
                await _context.Database
                    .SqlQueryRaw<ReportPdfLookupViewModel>(
                        """
                        SELECT TOP 1

                            Id,

                            PdfPath

                        FROM Reports

                        WHERE
                            Id = {0}
                        """,

                        id
                    )
                    .FirstOrDefaultAsync();


            if (report == null)
            {
                return NotFound();
            }


            if (
                string.IsNullOrWhiteSpace(
                    report.PdfPath)
            )
            {
                return NotFound();
            }


            // =====================================================
            // GET PHYSICAL PATH
            // =====================================================

            var filePath =
                GetPhysicalPdfPath(
                    report.PdfPath
                );


            if (filePath == null)
            {
                return NotFound();
            }


            // =====================================================
            // READ FILE
            // =====================================================

            var bytes =
                await System.IO.File.ReadAllBytesAsync(
                    filePath
                );


            // =====================================================
            // OPEN PDF IN BROWSER
            // =====================================================

            return File(
                bytes,
                "application/pdf"
            );
        }


        // =========================================================
        // DOWNLOAD PDF
        // =========================================================

        [HttpGet]
        public async Task<IActionResult> DownloadPdf(
            int id)
        {
            if (id <= 0)
            {
                return NotFound();
            }


            // =====================================================
            // GET REPORT
            // =====================================================

            var report =
                await _context.Database
                    .SqlQueryRaw<ReportPdfLookupViewModel>(
                        """
                        SELECT TOP 1

                            Id,

                            PdfPath

                        FROM Reports

                        WHERE
                            Id = {0}
                        """,

                        id
                    )
                    .FirstOrDefaultAsync();


            if (report == null)
            {
                return NotFound();
            }


            if (
                string.IsNullOrWhiteSpace(
                    report.PdfPath)
            )
            {
                return NotFound();
            }


            // =====================================================
            // PHYSICAL FILE
            // =====================================================

            var filePath =
                GetPhysicalPdfPath(
                    report.PdfPath
                );


            if (filePath == null)
            {
                return NotFound();
            }


            // =====================================================
            // FILE NAME
            // =====================================================

            var fileName =
                Path.GetFileName(
                    filePath
                );


            // =====================================================
            // READ
            // =====================================================

            var bytes =
                await System.IO.File.ReadAllBytesAsync(
                    filePath
                );


            // =====================================================
            // DOWNLOAD
            // =====================================================

            return File(
                bytes,
                "application/pdf",
                fileName
            );
        }


        // =========================================================
        // GET PHYSICAL PDF PATH
        // =========================================================

        private string? GetPhysicalPdfPath(
            string? pdfPath)
        {
            if (
                string.IsNullOrWhiteSpace(
                    pdfPath)
            )
            {
                return null;
            }


            // =====================================================
            // NORMALIZE PATH
            // =====================================================

            var normalizedPath =
                pdfPath
                    .Replace(
                        "\\",
                        "/"
                    )
                    .Trim();


            // =====================================================
            // GET FILE NAME ONLY
            // Prevent path traversal
            // =====================================================

            var fileName =
                Path.GetFileName(
                    normalizedPath
                );


            if (
                string.IsNullOrWhiteSpace(
                    fileName)
            )
            {
                return null;
            }


            // Report Location

            var reportsDirectory =
                Path.Combine(
                    _environment.WebRootPath,
                    "reports"
                );


            var filePath =
                Path.Combine(
                    reportsDirectory,
                    fileName
                );


            // =====================================================
            // FILE EXISTS
            // =====================================================

            if (
                !System.IO.File.Exists(
                    filePath)
            )
            {
                return null;
            }


            return filePath;
        }


        // =========================================================
        // PRIVATE PDF LOOKUP MODEL
        // =========================================================

        private class ReportPdfLookupViewModel
        {
            public int Id { get; set; }

            public string? PdfPath { get; set; }
        }
    }
}